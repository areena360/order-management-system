const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('../OMS_Frontend/node_modules/typescript');
const rx = require('../OMS_Frontend/node_modules/rxjs');
const source = fs.readFileSync('OMS_Frontend/src/app/orders/manage-orders/manage-orders.component.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, experimentalDecorators: true }}).outputText;
const sandbox = { exports: {}, setTimeout() {}, require: name => name === 'rxjs' ? rx : new Proxy({}, { get: (_, key) => key === 'inject' ? () => ({ detectChanges() {} }) : () => () => {} }) };
vm.runInNewContext(compiled, sandbox);
let calls = [], failIds = new Set(), rows = [], reads = 0;
const service = {
  updateStatus(id, statusId) { calls.push({id, statusId}); return failIds.has(id) ? rx.throwError(() => new Error('failed')) : rx.of({}); },
  getOrders() { reads++; return rx.of({items: rows, totalCount: rows.length}); }
};
const component = new sandbox.exports.ManageOrdersComponent(service, {}, {}, {}, {});
const order = (id, status = 'Pending') => ({ id, status });
rows = [order(1), order(2), order(3, 'Ready')];
component.orders = rows;
component.statuses = [{id: 5, name: 'Ready'}];
component.loading = false;
component.canEdit = true;
component.toggleOrderSelection(rows[0]);
assert.equal(component.somePageOrdersSelected, true);
assert.equal(component.allPageOrdersSelected, false);
component.togglePageSelection();
assert.equal(component.allPageOrdersSelected, true);
component.togglePageSelection();
assert.equal(component.selectedOrderIds.size, 0);
component.togglePageSelection();
failIds.add(2);
component.updateSelectedStatuses(5);
assert.deepEqual(calls.map(x => x.id), [1,2], 'Only changed selected orders are requested');
assert.equal(component.selectedOrderIds.size, 1);
assert.equal(component.selectedOrderIds.has(2), true, 'Only failures remain selected');
assert.match(component.bulkStatusMessage, /1 order\(s\) updated/);
assert.match(component.bulkStatusMessage, /1 already/);
assert.match(component.bulkStatusMessage, /1 failed/);
assert.equal(component.bulkStatusSaving, false);
failIds.clear();
component.updateSelectedStatuses(5);
assert.equal(component.selectedOrderIds.size, 0);
assert.equal(component.bulkStatusHasErrors, false);
component.toggleOrderSelection(rows[2]);
const count = calls.length;
component.updateSelectedStatuses(5);
assert.equal(calls.length, count, 'No-op status does not write history');
component.canEdit = false;
component.togglePageSelection();
component.updateSelectedStatuses(5);
assert.equal(calls.length, count);
assert.equal(component.selectedOrderIds.size, 0);
component.canEdit = true;
component.togglePageSelection();
const readCount = reads;
component.silentRefresh();
assert.equal(reads, readCount, 'Polling cannot replace selected rows');
component.fetchOrders();
assert.equal(component.selectedOrderIds.size, 0, 'Page/filter fetch clears selection');
const delayed = new rx.Subject();
service.updateStatus = () => delayed;
component.toggleOrderSelection(rows[0]);
component.updateSelectedStatuses(5);
assert.equal(component.bulkStatusSaving, true);
component.toggleOrderSelection(rows[1]);
assert.equal(component.selectedOrderIds.size, 1, 'Selection locked while saving');
component.changeOrderStatus(rows[1], 5);
assert.equal(component.statusSavingId, null, 'Inline status blocked during bulk update');
delayed.next({}); delayed.complete();
assert.equal(component.bulkStatusSaving, false);
console.log('PASS: page selection, mixed selection, partial failure/retry, unchanged status, permissions, polling, page reset, concurrent-edit guards');
